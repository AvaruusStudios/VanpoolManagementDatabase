            SQL_CREATE_VEHICLE_RECORD = QueryLoader.getQuery("vehicle/insertVehicle.sql");
            SQL_READ_VEHICLE_RECORD = QueryLoader.getQuery("vehicle/selectVehicleById.sql");
            SQL_READ_ALL_VEHICLE_RECORDS = QueryLoader.getQuery("vehicle/selectAllVehicles.sql");
            SQL_COUNT_VEHICLE_RECORDS = QueryLoader.getQuery("vehicle/countVehicles.sql");
            SQL_EXISTS_VEHICLE_BY_ID = QueryLoader.getQuery("vehicle/existsVehicleById.sql");
            SQL_UPDATE_VEHICLE_RECORD = QueryLoader.getQuery("vehicle/updateVehicle.sql");
