    /**
     * <p>
     * Maps a row from a {@link ResultSet} to a {@link Vehicle} object.
     * </p>
     *
     * @param rs The {@link ResultSet} positioned at the current row containing vehicle data.
     * @return A fully populated {@link Vehicle} object with data retrieved from the {@code ResultSet}.
     * @throws SQLException If a database access error occurs.
     */
    private Vehicle mapResultSetToVehicle(ResultSet rs) throws SQLException {
        Vehicle vehicle = new Vehicle();
        Integer vehicleId = rs.getInt("VehicleID");
        if (vehicleId > 0) {
            vehicle._setVehicleID(vehicleId);
        }

        vehicle.setMake(rs.getString("Make"));
        vehicle.setModel(rs.getString("Model"));
        vehicle.setManufactureYear(rs.getInt("ManufactureYear"));
        vehicle.setLicensePlate(rs.getString("LicensePlate"));
        vehicle.setPassengerCapacity(rs.getInt("PassengerCapacity"));
        vehicle.setVehicleNumber(rs.getString("VehicleNumber"));

        vehicle.setIsActive(rs.getInt("IsActive") == 1);

        String deletedAtStr = rs.getString("DeletedAt");
        vehicle.setDeletedAt(deletedAtStr != null && !deletedAtStr.isEmpty() ? LocalDateTime.parse(deletedAtStr, CUSTOM_DATETIME_FORMATTER) : null);

        return vehicle;
    }

    /**
     * {@inheritDoc}
     */
    @Override
    public Vehicle create(Vehicle vehicle) throws DatabaseAccessException {
        Objects.requireNonNull(vehicle, "Vehicle object cannot be null for creation.");
        if (vehicle.getVehicleID() != null) {
            throw new IllegalArgumentException("Vehicle ID must be null for new vehicle creation (auto-generated).");
        }
        Objects.requireNonNull(vehicle.getMake(), "Make cannot be null for vehicle creation.");
        Objects.requireNonNull(vehicle.getModel(), "Model cannot be null for vehicle creation.");
        Objects.requireNonNull(vehicle.getLicensePlate(), "LicensePlate cannot be null for vehicle creation.");
        Objects.requireNonNull(vehicle.getVehicleNumber(), "VehicleNumber cannot be null for vehicle creation.");


        try (Connection conn = DatabaseManager.getConnection();
             PreparedStatement stmt = conn.prepareStatement(SQL_CREATE_VEHICLE_RECORD, Statement.RETURN_GENERATED_KEYS)) {

            stmt.setString(1, vehicle.getMake());
            stmt.setString(2, vehicle.getModel());
            stmt.setInt(3, vehicle.getManufactureYear());
            stmt.setString(4, vehicle.getLicensePlate());
            stmt.setInt(5, vehicle.getPassengerCapacity());
            stmt.setInt(7, vehicle.isActive() ? 1 : 0);
            stmt.setString(8, vehicle.getDeletedAt() != null ? vehicle.getDeletedAt().format(CUSTOM_DATETIME_FORMATTER) : null);
            stmt.setString(9, vehicle.getVehicleNumber());

            logger.debug("Executing insert vehicle query for license plate: {}", vehicle.getLicensePlate());
            int affectedRows = stmt.executeUpdate();

            if (affectedRows == 0) {
                logger.error("Creating vehicle failed, no rows affected for license plate: {}", vehicle.getLicensePlate());
                throw new DatabaseAccessException("Creating vehicle failed, no rows affected.");
            }

            try (ResultSet generatedKeys = stmt.getGeneratedKeys()) {
                if (generatedKeys.next()) {
                    Integer generatedId = generatedKeys.getInt(1);
                    vehicle._setVehicleID(generatedId);
                    logger.info("Successfully created vehicle with ID: {}", generatedId);
                    return vehicle;
                } else {
                    logger.error("Creating vehicle failed, no ID obtained for license plate: {}", vehicle.getLicensePlate());
                    throw new DatabaseAccessException("Creating vehicle failed, no ID obtained.");
                }
            }
        } catch (SQLException e) {
            logger.error("Error creating vehicle record: {}", e.getMessage(), e);
            throw new DatabaseAccessException("Error creating vehicle record: " + e.getMessage(), e);
        }
    }

    /**
     * {@inheritDoc}
     */
    @Override
    public boolean delete(Integer id) throws DatabaseAccessException {
        Objects.requireNonNull(id, "Vehicle ID cannot be null for deletion.");
        try (Connection conn = DatabaseManager.getConnection();
             PreparedStatement stmt = conn.prepareStatement(SQL_DELETE_VEHICLE_SOFT)) {

            stmt.setString(1, LocalDateTime.now().format(CUSTOM_DATETIME_FORMATTER));
            stmt.setInt(2, id);

            logger.debug("Executing soft-delete vehicle query for ID: {}", id);
            int affectedRows = stmt.executeUpdate();

            if (affectedRows == 0) {
                logger.warn("No vehicle found with ID: {} for soft-deletion.", id);
                return false;
            } else {
                logger.info("Successfully soft-deleted vehicle with ID: {}", id);
                return true;
            }
        } catch (SQLException e) {
            logger.error("Error soft-deleting vehicle record with ID {}: {}", id, e.getMessage(), e);
            throw new DatabaseAccessException("Error soft-deleting vehicle record: " + e.getMessage(), e);
        }
    }

    /**
     * {@inheritDoc}
     */
    @Override
    public Optional<Vehicle> find(Integer id) throws DatabaseAccessException {
        Objects.requireNonNull(id, "Vehicle ID cannot be null for reading.");
        try (Connection conn = DatabaseManager.getConnection();
             PreparedStatement stmt = conn.prepareStatement(SQL_READ_VEHICLE_RECORD)) {

            stmt.setInt(1, id);
            logger.debug("Executing read vehicle query for ID: {}", id);
            try (ResultSet rs = stmt.executeQuery()) {
                if (rs.next()) {
                    Vehicle vehicle = mapResultSetToVehicle(rs);
                    logger.info("Found vehicle with ID: {}", id);
                    return Optional.of(vehicle);
                } else {
                    logger.info("No vehicle found with ID: {}", id);
                    return Optional.empty();
                }
            }
        } catch (SQLException e) {
            logger.error("Error reading vehicle record with ID {}: {}", id, e.getMessage(), e);
            throw new DatabaseAccessException("Error reading vehicle record: " + e.getMessage(), e);
        }
    }

    /**
     * {@inheritDoc}
     */
    @Override
    public List<Vehicle> findAll() throws DatabaseAccessException {
        List<Vehicle> vehicles = new ArrayList<>();
        try (Connection conn = DatabaseManager.getConnection();
             PreparedStatement stmt = conn.prepareStatement(SQL_READ_ALL_VEHICLE_RECORDS);
             ResultSet rs = stmt.executeQuery()) {

            logger.debug("Executing read all vehicles query.");
            while (rs.next()) {
                vehicles.add(mapResultSetToVehicle(rs));
            }
            logger.info("Found {} total vehicles.", vehicles.size());
        } catch (SQLException e) {
            logger.error("Error reading all vehicle records: {}", e.getMessage(), e);
            throw new DatabaseAccessException("Error reading all vehicle records: " + e.getMessage(), e);
        }
        return vehicles;
    }

    /**
     * {@inheritDoc}
     */
    @Override
    public List<Vehicle> findActive() throws DatabaseAccessException {
        List<Vehicle> activeVehicles = new ArrayList<>();
        try (Connection conn = DatabaseManager.getConnection();
             PreparedStatement stmt = conn.prepareStatement(SQL_SELECT_ACTIVE_VEHICLE);
             ResultSet rs = stmt.executeQuery()) {

            logger.debug("Executing find active vehicles query.");
            while (rs.next()) {
                activeVehicles.add(mapResultSetToVehicle(rs));
            }
            logger.info("Found {} active vehicles.", activeVehicles.size());

            // A business rule violation would be more than one active vehicle, which is handled in the application logic.
            // The method signature requires a list, so we return all found.
            return activeVehicles;

        } catch (SQLException e) {
            logger.error("Error finding active vehicles: {}", e.getMessage(), e);
            throw new DatabaseAccessException("Error finding active vehicles: " + e.getMessage(), e);
        }
    }


