    /** SQL query to soft-delete a vehicle record by updating its `IsActive` flag and `DeletedAt` timestamp. Loaded from `vehicle/deleteVehicleSoft.sql`. */
    private static final String SQL_DELETE_VEHICLE_SOFT;
