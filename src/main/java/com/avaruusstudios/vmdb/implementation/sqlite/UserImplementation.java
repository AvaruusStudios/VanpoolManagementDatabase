/**
 * <p>
 * Concrete implementation of the {@link UserDataAccess} interface for managing
 * {@link User} data in an SQLite database. This class fully implements all generic
 * CRUD and read operations inherited via {@link GenericDataAccess}, along with
 * specific queries for {@code User} entities (e.g., finding by Windows username or role).
 * </p>
 *
 * <p>
 * This implementation leverages {@link DatabaseManager} to obtain and manage database
 * connections, and {@link QueryLoader} to dynamically load SQL queries from external
 * `.sql` files. This design promotes separation of concerns and facilitates easier
 * maintenance of SQL statements.
 * </p>
 *
 * <p>
 * Key characteristics of this implementation include:
 * </p>
 * <ul>
 * <li>User IDs are auto-generated by the database upon insertion.</li>
 * <li>Uniqueness of `WindowsUsername` is enforced at the database level via a unique constraint.</li>
 * <li>Deletion of user records is implemented as a **soft-delete**, meaning records are
 * deactivated by updating their `IsActive` flag to `0` (false) and setting the
 * `DeletedAt` timestamp, rather than physically removing them from the database.</li>
 * <li>`LocalDateTime` objects are persisted as `TEXT` in the SQLite database using a
 * custom format ("dd-MMM-yyyy HH:mm") and parsed back from this format.</li>
 * <li>`boolean` values (e.g., for `IsActive`) are stored as `INTEGER` (`1` for true, `0` for false)
 * in the SQLite database.</li>
 * <li>All {@link SQLException}s originating from database interactions are
 * wrapped into custom {@link DatabaseAccessException}s, providing a consistent
 * layer for error handling across the DAO.</li>
 * </ul>
 *
 * @author AvaruusStudios
 * @version 1.0
 * Created On: 2025-07-14
 * Updated On: 2025-07-14
 *
 * @see UserDataAccess
 * @see User
 * @see Role
 * @see DatabaseManager
 * @see QueryLoader
 * @see DatabaseAccessException
 * @see GenericDataAccess
 * @see CreateDataAccess
 * @see ReadDataAccess
 * @see UpdateDataAccess
 */
