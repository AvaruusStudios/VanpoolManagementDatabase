    /**
     * <p>
     * Updates an existing {@link Participant} record in the database. The update operation is
     * based on the `ParticipantID` of the provided {@link Participant} object.
     * </p>
     * <p>
     * This method validates the provided {@code Participant} object and its mandatory fields
     * before execution. It specifically handles unique constraint violations if the updated
     * participant details (e.g., `Email`) conflict with an existing record's unique attributes.
     * </p>
     *
     * @param participant The {@link Participant} object containing the updated data.
     * Its `ParticipantID` must not be {@code null} and must be positive to identify the record to update.
     * @throws DatabaseAccessException  if a database access error occurs during the update.
     * @throws NullPointerException     if the provided {@code participant} object itself, its `ParticipantID`,
     * or any of its required `NOT NULL` fields are {@code null}.
     * @throws IllegalArgumentException if the `ParticipantID` is non-positive, if any
     * mandatory string fields are empty after trimming, or if foreign keys are invalid.
     */
    @Override
    public void updateRecord(Participant participant) throws DatabaseAccessException {
        Objects.requireNonNull(participant, "Participant object cannot be null for update.");
        Objects.requireNonNull(participant.getParticipantID(), "Participant ID cannot be null for update.");
        if (participant.getParticipantID() <= 0) {
            throw new IllegalArgumentException("Participant ID must be positive for update.");
        }
        Objects.requireNonNull(participant.getFirstName(), "First Name cannot be null for update.");
        Objects.requireNonNull(participant.getLastName(), "Last Name cannot be null for update.");
        Objects.requireNonNull(participant.getEmail(), "Email cannot be null for update.");
        Objects.requireNonNull(participant.getPhone(), "Phone cannot be null for update.");
        Objects.requireNonNull(participant.getDistanceMiles(), "Distance Miles cannot be null for update.");
        Objects.requireNonNull(participant.getJoinDate(), "Join Date cannot be null for update.");
        Objects.requireNonNull(participant.getProgram(), "Program cannot be null for update.");
        Objects.requireNonNull(participant.getRole(), "Role cannot be null for update.");
        Objects.requireNonNull(participant.getPickUpLocation(), "Pickup Location cannot be null for update.");
        Objects.requireNonNull(participant.getDropOffLocation(), "Drop-off Location cannot be null for update.");
        Objects.requireNonNull(participant.getPickUpLocation().getLocationID(), "Pickup Location ID cannot be null for update."); // Corrected
        Objects.requireNonNull(participant.getDropOffLocation().getLocationID(), "Drop-off Location ID cannot be null for update."); // Corrected


        if (participant.getFirstName().trim().isEmpty() ||
                participant.getLastName().trim().isEmpty() ||
                participant.getEmail().trim().isEmpty() ||
                participant.getPhone().trim().isEmpty()) {
            throw new IllegalArgumentException("Mandatory string fields (first name, last name, email, phone) cannot be empty for participant update.");
        }
        // Removed redundant BigDecimal validation here, it's handled in Participant model setter

        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_UPDATE_PARTICIPANT_RECORD)) {

            pstmt.setString(1, participant.getFirstName().trim());
            pstmt.setString(2, participant.getMiddleName() != null ? participant.getMiddleName().trim() : null);
            pstmt.setString(3, participant.getLastName().trim());
            pstmt.setString(4, participant.getEmail().trim());
            pstmt.setString(5, participant.getPhone().trim());
            pstmt.setDouble(6, participant.getDistanceMiles().doubleValue()); // Corrected
            pstmt.setString(7, participant.getJoinDate().format(CUSTOM_DATE_FORMATTER));
            // Corrected: Ensure benefit amount is handled as double for DB
            pstmt.setDouble(8, participant.getBenefitAmount() != null ? participant.getBenefitAmount().doubleValue() : 0.0);
            pstmt.setString(9, participant.getRole().name()); // Store enum name
            pstmt.setString(10, participant.getProgram().name()); // Store Program enum name

            // Location FKeys
            if (participant.getPickUpLocation() != null && participant.getPickUpLocation().getLocationID() != null) { // Corrected
                pstmt.setInt(11, participant.getPickUpLocation().getLocationID()); // Corrected
            } else {
                pstmt.setNull(11, Types.INTEGER);
            }

            if (participant.getDropOffLocation() != null && participant.getDropOffLocation().getLocationID() != null) { // Corrected
                pstmt.setInt(12, participant.getDropOffLocation().getLocationID()); // Corrected
            } else {
                pstmt.setNull(12, Types.INTEGER);
            }

            pstmt.setInt(13, participant.getIsActive() ? 1 : 0);

            if (participant.getDeletedAt() != null) {
                pstmt.setString(14, participant.getDeletedAt().format(CUSTOM_DATETIME_FORMATTER));
            } else {
                pstmt.setNull(14, Types.VARCHAR);
            }

            pstmt.setString(15, participant.getNotes() != null ? participant.getNotes().trim() : null);
            pstmt.setInt(16, participant.getParticipantID()); // WHERE clause ID

            int affectedRows = pstmt.executeUpdate();
            if (affectedRows == 0) {
                logger.warn("Update participant with ID {} affected 0 rows. Participant might not exist or data was identical.", participant.getParticipantID());
                throw new DatabaseAccessException("Participant with ID " + participant.getParticipantID() + " not found for update or no changes were made.");
            } else {
                logger.info("Participant with ID {} updated successfully. Affected rows: {}.", participant.getParticipantID(), affectedRows);
            }

        } catch (SQLException e) {
            logger.error("Error updating participant with ID {}: {}", participant.getParticipantID(), e.getMessage(), e);
            if (e.getErrorCode() == 19) { // SQLite unique constraint violation
                String errorMessage = "Failed to update participant. It might already exist or a unique constraint was violated.";
                if (e.getMessage().contains("UNIQUE constraint failed: Participants.Email")) {
                    errorMessage = "Participant with email '" + participant.getEmail() + "' already exists. Email addresses must be unique.";
                }
                throw new DatabaseAccessException(errorMessage, e);
            }
            throw new DatabaseAccessException("Failed to update participant with ID " + participant.getParticipantID() + ": " + e.getMessage(), e);
        } catch (IllegalArgumentException e) {
            logger.error("Participant validation error during update for participant ID {}: {}", participant.getParticipantID(), e.getMessage(), e);
            throw new DatabaseAccessException("Participant data is invalid for update: " + e.getMessage(), e);
        }
    }

    /**
     * <p>
     * Soft-deletes a {@link Participant} record from the database by setting its `IsActive` flag
     * to `0` (false) and updating the `DeletedAt` timestamp to the current date and time.
     * This method does not physically remove the record, preserving historical data.
     * </p>
     *
     * @param id The unique integer ID of the participant to soft-delete. Must not be {@code null} and must be positive.
     * @throws DatabaseAccessException  if a database access error occurs during the soft-deletion.
     * @throws NullPointerException     if the provided {@code id} is {@code null}.
     * @throws IllegalArgumentException if the provided {@code id} is non-positive.
     */
    @Override
    public void deleteRecord(Integer id) throws DatabaseAccessException {
        Objects.requireNonNull(id, "Participant ID cannot be null for deletion.");
        if (id <= 0) {
            throw new IllegalArgumentException("Participant ID must be positive for deletion.");
        }

        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_DELETE_PARTICIPANT_SOFT)) {

            pstmt.setString(1, LocalDateTime.now().format(CUSTOM_DATETIME_FORMATTER));
            pstmt.setInt(2, id);

            int affectedRows = pstmt.executeUpdate();
            if (affectedRows == 0) {
                logger.warn("Soft-delete participant with ID {} affected 0 rows. Participant might not exist or already soft-deleted.", id);
                throw new DatabaseAccessException("Participant with ID " + id + " not found for soft-deletion or already deleted.");
            } else {
                logger.info("Participant with ID {} soft-deleted successfully (IsActive=0, DeletedAt={}).", id, LocalDateTime.now().format(CUSTOM_DATETIME_FORMATTER));
            }
        } catch (SQLException e) {
            logger.error("Error soft-deleting participant with ID {}: {}", id, e.getMessage(), e);
            throw new DatabaseAccessException("Failed to soft-delete participant with ID " + id + ": " + e.getMessage(), e);
        }
    }

