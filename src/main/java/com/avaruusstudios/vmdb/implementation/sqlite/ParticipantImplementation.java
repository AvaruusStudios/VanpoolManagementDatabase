/**
 * <p>
 * Concrete implementation of the {@link ParticipantDataAccess} interface for managing
 * {@link Participant} data in an SQLite database. This class fully implements all generic
 * CRUD and read operations inherited via the decoupled data access interfaces, along with
 * specific queries for {@code Participant} entities (e.g., finding by email, counting/retrieving
 * active participants, or filtering by program/role).
 * </p>
 *
 * <p>
 * This implementation leverages {@link DatabaseManager} to obtain and manage database
 * connections, and {@link QueryLoader} to dynamically load SQL queries from external
 * `.sql` files. This design promotes separation of concerns and facilitates easier
 * maintenance of SQL statements.
 * </p>
 *
 * <p>
 * Key characteristics of this implementation include:
 * </p>
 * <ul>
 * <li>Participant IDs are auto-generated by the database upon insertion.</li>
 * <li>Uniqueness of `Email` is enforced at the database level.</li>
 * <li>Deletion of participant records is implemented as a **soft-delete**, meaning records are
 * deactivated by updating their `IsActive` flag to `0` (false) and setting the
 * `DeletedAt` timestamp, rather than physically removing them from the database.</li>
 * <li>`LocalDate` objects (e.g., `JoinDate`) are persisted as `TEXT` in the SQLite database
 * using a "yyyy-MM-dd" format.</li>
 * <li>`LocalDateTime` objects (e.g., `DeletedAt`) are persisted as `TEXT` in the SQLite database
 * using a "dd-MMM-yyyy HH:mm" format.</li>
 * <li>`BigDecimal` objects (e.g., `BenefitAmount`) are stored as `REAL` (floating-point)
 * in the SQLite database. Precision considerations are managed during conversion.</li>
 * <li>`boolean` values (e.g., for `IsActive`) are stored as `INTEGER` (`1` for true, `0` for false)
 * in the SQLite database.</li>
 * <li>`Role` enum values are stored as `TEXT` in the SQLite database. Conversion between
 * `String` and `Role` enum uses the robust {@link Role#fromDbValue(String)} method.</li>
 * <li>**NEW**: `Program` enum values are stored as `TEXT` in the SQLite database. Conversion between
 * `String` and `Program` enum uses the robust {@link Program#fromDbValue(String)} method.</li>
 * <li>All {@link SQLException}s originating from database interactions are
 * wrapped into custom {@link DatabaseAccessException}s, providing a consistent
 * layer for error handling across the DAO.</li>
 * </ul>
 *
 * @author AvaruusStudios
 * @version 1.2
 * Created On: 2025-07-22
 * Updated On: 2025-07-22 (Updated Program and Role to Enum handling, fixed method names)
 *
 * @see ParticipantDataAccess
 * @see Participant
 * @see DatabaseManager
 * @see QueryLoader
 * @see DatabaseAccessException
 * @see CreateDataAccess
 * @see ReadDataAccess
 * @see UpdateDataAccess
 * @see DeleteDataAccess
 */
