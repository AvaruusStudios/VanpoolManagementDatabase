    /**
     * <p>
     * Maps a row from a {@link ResultSet} to a {@link Participant} object.
     * This private helper method centralizes the logic for converting raw database
     * column values into a populated {@code Participant} model object, ensuring data consistency
     * and type safety across all read operations.
     * </p>
     * <p>
     * It handles:
     * <ul>
     * <li>Retrieval of the auto-generated `ParticipantID` and setting it via the `_setParticipantID` method.</li>
     * <li>String fields (e.g., `FirstName`, `MiddleName`, `LastName`, `Email`, `Phone`, `Notes`).</li>
     * <li>`BigDecimal` for `BenefitAmount` and `DistanceMiles`.</li>
     * <li>`LocalDate` for `JoinDate`.</li>
     * <li>Conversion of `IsActive` from `INTEGER` (0 or 1) to `boolean`.</li>
     * <li>Handling of nullable `DeletedAt` `TEXT` field, parsing it into
     * {@link LocalDateTime} objects.</li>
     * <li>Mapping of foreign key IDs (`PickUpLocationID_FK`, `DropOffLocationID_FK`) to {@link Location} objects.</li>
     * <li>Mapping of `Role` enum using {@link Role#fromDbValue(String)}.</li>
     * <li>Mapping of `Program` enum using {@link Program#fromDbValue(String)}.</li>
     * </ul>
     * </p>
     *
     * @param rs The {@link ResultSet} positioned at the current row containing participant data.
     * @return A fully populated {@link Participant} object with data retrieved from the {@code ResultSet}.
     * @throws SQLException If a database access error occurs (e.g., a column name is not found,
     * or there is a data type mismatch during retrieval).
     */
    private Participant mapResultSetToParticipant(ResultSet rs) throws SQLException {
        Participant participant = new Participant();
        Integer participantId = rs.getInt("ParticipantID");
        if (participantId > 0) { // SQLite getInt returns 0 for NULL for INTEGER PRIMARY KEY, check for positive valid ID
            participant._setParticipantID(participantId);
        }

        participant.setFirstName(rs.getString("FirstName"));
        participant.setMiddleName(rs.getString("MiddleName"));
        participant.setLastName(rs.getString("LastName"));
        participant.setEmail(rs.getString("Email"));
        participant.setPhone(rs.getString("Phone"));
        participant.setDistanceMiles(BigDecimal.valueOf(rs.getDouble("DistanceMiles"))); // Corrected

        // JoinDate
        String joinDateStr = rs.getString("JoinDate");
        participant.setJoinDate(joinDateStr != null && !joinDateStr.isEmpty() ?
                LocalDate.parse(joinDateStr, CUSTOM_DATE_FORMATTER) : null);

        // BenefitAmount
        participant.setBenefitAmount(BigDecimal.valueOf(rs.getDouble("BenefitAmount")));

        // Role Enum
        String roleStr = rs.getString("Role");
        participant.setRole(roleStr != null && !roleStr.isEmpty() ? Role.fromDbValue(roleStr) : null);

        // Program Enum
        String programStr = rs.getString("Program");
        participant.setProgram(programStr != null && !programStr.isEmpty() ? Program.fromDbValue(programStr) : null);

        // Location FKeys - Map to Location objects
        Integer pickUpLocationId = rs.getObject("PickUpLocationID_FK", Integer.class);
        if (pickUpLocationId != null) {
            Location pickUpLoc = new Location();
            pickUpLoc._setLocationID(pickUpLocationId); // Corrected to use _setLocationID
            participant.setPickUpLocation(pickUpLoc);
        } else {
            participant.setPickUpLocation(null);
        }

        Integer dropOffLocationId = rs.getObject("DropOffLocationID_FK", Integer.class);
        if (dropOffLocationId != null) {
            Location dropOffLoc = new Location();
            dropOffLoc._setLocationID(dropOffLocationId); // Corrected to use _setLocationID
            participant.setDropOffLocation(dropOffLoc);
        } else {
            participant.setDropOffLocation(null);
        }

        participant.setIsActive(rs.getInt("IsActive") == 1);

        String deletedAtStr = rs.getString("DeletedAt");
        participant.setDeletedAt(deletedAtStr != null && !deletedAtStr.isEmpty() ?
                LocalDateTime.parse(deletedAtStr, CUSTOM_DATETIME_FORMATTER) : null);

        participant.setNotes(rs.getString("Notes"));

        return participant;
    }

    /**
     * <p>
     * Inserts a new {@link Participant} record into the SQLite database.
     * The database's `AUTOINCREMENT` feature automatically assigns a unique `ParticipantID`.
     * </p>
     * <p>
     * This method validates the provided {@code Participant} object and its mandatory fields
     * (`FirstName`, `LastName`, `Email`, `Phone`, `DistanceMiles`, `JoinDate`, `Program`, `Role`)
     * before attempting the insertion. It handles potential database errors, including unique constraint violations
     * for `Email`. Upon successful insertion, the database-generated `ParticipantID` is injected
     * back into the provided `Participant` object.
     * </p>
     *
     * @param participant The {@link Participant} object to be created. Its `ParticipantID` will be ignored if present,
     * as it's auto-generated by the database.
     * @return The created {@link Participant} object, updated with its database-assigned `ParticipantID`.
     * @throws DatabaseAccessException  if a database access error occurs during creation,
     * e.g., a unique constraint violation, or other SQL errors.
     * @throws NullPointerException     if the provided {@code participant} object or any of its
     * required `NOT NULL` fields are {@code null}.
     * @throws IllegalArgumentException if any mandatory string fields are empty after trimming,
     * or if foreign keys are invalid.
     */
    @Override
    public Participant createRecord(Participant participant) throws DatabaseAccessException {
        Objects.requireNonNull(participant, "Participant object cannot be null for creation.");
        Objects.requireNonNull(participant.getFirstName(), "First Name cannot be null for creation.");
        Objects.requireNonNull(participant.getLastName(), "Last Name cannot be null for creation.");
        Objects.requireNonNull(participant.getEmail(), "Email cannot be null for creation.");
        Objects.requireNonNull(participant.getPhone(), "Phone cannot be null for creation.");
        Objects.requireNonNull(participant.getDistanceMiles(), "Distance Miles cannot be null for creation.");
        Objects.requireNonNull(participant.getJoinDate(), "Join Date cannot be null for creation.");
        Objects.requireNonNull(participant.getProgram(), "Program cannot be null for creation.");
        Objects.requireNonNull(participant.getRole(), "Role cannot be null for creation.");
        Objects.requireNonNull(participant.getPickUpLocation(), "Pickup Location cannot be null for creation.");
        Objects.requireNonNull(participant.getDropOffLocation(), "Drop-off Location cannot be null for creation.");
        Objects.requireNonNull(participant.getPickUpLocation().getLocationID(), "Pickup Location ID cannot be null for creation."); // Corrected
        Objects.requireNonNull(participant.getDropOffLocation().getLocationID(), "Drop-off Location ID cannot be null for creation."); // Corrected


        if (participant.getFirstName().trim().isEmpty() ||
                participant.getLastName().trim().isEmpty() ||
                participant.getEmail().trim().isEmpty() ||
                participant.getPhone().trim().isEmpty()) {
            throw new IllegalArgumentException("Mandatory string fields (first name, last name, email, phone) cannot be empty for participant creation.");
        }
        // Removed redundant BigDecimal validation here, it's handled in Participant model setter

        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_CREATE_PARTICIPANT_RECORD, Statement.RETURN_GENERATED_KEYS)) {

            pstmt.setString(1, participant.getFirstName().trim());
            pstmt.setString(2, participant.getMiddleName() != null ? participant.getMiddleName().trim() : null);
            pstmt.setString(3, participant.getLastName().trim());
            pstmt.setString(4, participant.getEmail().trim());
            pstmt.setString(5, participant.getPhone().trim());
            pstmt.setDouble(6, participant.getDistanceMiles().doubleValue()); // Corrected
            pstmt.setString(7, participant.getJoinDate().format(CUSTOM_DATE_FORMATTER));
            // Corrected: Ensure benefit amount is handled as double for DB
            pstmt.setDouble(8, participant.getBenefitAmount() != null ? participant.getBenefitAmount().doubleValue() : 0.0);
            pstmt.setString(9, participant.getRole().name()); // Store enum name
            pstmt.setString(10, participant.getProgram().name()); // Store Program enum name

            // Location FKeys
            if (participant.getPickUpLocation() != null && participant.getPickUpLocation().getLocationID() != null) { // Corrected
                pstmt.setInt(11, participant.getPickUpLocation().getLocationID()); // Corrected
            } else {
                pstmt.setNull(11, Types.INTEGER);
            }

            if (participant.getDropOffLocation() != null && participant.getDropOffLocation().getLocationID() != null) { // Corrected
                pstmt.setInt(12, participant.getDropOffLocation().getLocationID()); // Corrected
            } else {
                pstmt.setNull(12, Types.INTEGER);
            }

            pstmt.setInt(13, participant.getIsActive() ? 1 : 0);

            if (participant.getDeletedAt() != null) {
                pstmt.setString(14, participant.getDeletedAt().format(CUSTOM_DATETIME_FORMATTER));
            } else {
                pstmt.setNull(14, Types.VARCHAR);
            }

            pstmt.setString(15, participant.getNotes() != null ? participant.getNotes().trim() : null);

            int affectedRows = pstmt.executeUpdate();
            if (affectedRows == 0) {
                logger.error("Creating participant failed, no rows affected for email: {}.");
                throw new DatabaseAccessException("Creating participant failed, no rows affected.");
            }

            try (ResultSet generatedKeys = pstmt.getGeneratedKeys()) {
                if (generatedKeys.next()) {
                    participant._setParticipantID(generatedKeys.getInt(1));
                    logger.info("Participant created successfully with ID: {}.", participant.getParticipantID());
                } else {
                    logger.error("Creating participant failed, no ID obtained for email: {}.");
                    throw new DatabaseAccessException("Creating participant failed, no ID obtained.");
                }
            }
            return participant;

        } catch (SQLException e) {
            logger.error("Error creating participant '{}': {}", participant.getEmail(), e.getMessage(), e);
            if (e.getErrorCode() == 19) { // SQLite unique constraint violation
                String errorMessage = "Failed to create participant. It might already exist or a unique constraint was violated.";
                if (e.getMessage().contains("UNIQUE constraint failed: Participants.Email")) {
                    errorMessage = "Participant with email '" + participant.getEmail() + "' already exists. Email addresses must be unique.";
                }
                throw new DatabaseAccessException(errorMessage, e);
            }
            throw new DatabaseAccessException("Failed to create participant: " + e.getMessage(), e);
        } catch (IllegalArgumentException | IllegalStateException e) {
            logger.error("Participant validation/state error during creation for email '{}': {}", participant.getEmail(), e.getMessage(), e);
            throw new DatabaseAccessException("Participant data is invalid or in an illegal state for creation: " + e.getMessage(), e);
        }
    }

    /**
     * <p>
     * Retrieves a single {@link Participant} record from the database by its unique identifier (`ParticipantID`).
     * </p>
     *
     * @param id The unique integer ID of the participant to retrieve. Must not be {@code null} and must be positive.
     * @return An {@link Optional} containing the {@link Participant} object if a participant with the given ID is found,
     * or an empty {@link Optional} if no such participant exists.
     * @throws DatabaseAccessException  if a database access error occurs during retrieval.
     * @throws NullPointerException     if the provided {@code id} is {@code null}.
     * @throws IllegalArgumentException if the provided {@code id} is non-positive.
     */
    @Override
    public Optional<Participant> readRecord(Integer id) throws DatabaseAccessException {
        Objects.requireNonNull(id, "Participant ID cannot be null for retrieval.");
        if (id <= 0) {
            throw new IllegalArgumentException("Participant ID must be positive for retrieval.");
        }

        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_READ_PARTICIPANT_RECORD)) {

            pstmt.setInt(1, id);
            try (ResultSet rs = pstmt.executeQuery()) {
                if (rs.next()) {
                    return Optional.of(mapResultSetToParticipant(rs));
                }
            }
        } catch (SQLException e) {
            logger.error("Error retrieving participant by ID {}: {}", id, e.getMessage(), e);
            throw new DatabaseAccessException("Failed to retrieve participant by ID " + id + ": " + e.getMessage(), e);
        }
        return Optional.empty();
    }

    /**
     * <p>
     * Retrieves all {@link Participant} records currently stored in the database.
     * </p>
     *
     * @return A {@link List} of {@link Participant} objects. The list will be empty if no participants are found.
     * @throws DatabaseAccessException if a database access error occurs during retrieval.
     */
    @Override
    public List<Participant> readRecordAll() throws DatabaseAccessException {
        List<Participant> participants = new ArrayList<>();
        try (Connection connection = DatabaseManager.getConnection();
             Statement stmt = connection.createStatement();
             ResultSet rs = stmt.executeQuery(SQL_READ_ALL_PARTICIPANT_RECORDS)) {

            while (rs.next()) {
                participants.add(mapResultSetToParticipant(rs));
            }
        } catch (SQLException e) {
            logger.error("Error retrieving all participants: {}", e.getMessage(), e);
            throw new DatabaseAccessException("Failed to retrieve all participants: " + e.getMessage(), e);
        }
        return participants;
    }

