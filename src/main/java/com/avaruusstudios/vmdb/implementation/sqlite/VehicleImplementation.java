    private static final Logger logger = LoggerFactory.getLogger(VehicleImplementation.class);

    // Date/Time formatters for converting between LocalDate/LocalDateTime and TEXT in SQLite
    // Using Locale.ENGLISH for consistent month abbreviations (e.g., "Jan", "Feb")
    private static final DateTimeFormatter CUSTOM_DATE_FORMATTER = DateTimeFormatter.ofPattern("dd-MMM-yyyy", Locale.ENGLISH);
    private static final DateTimeFormatter CUSTOM_DATETIME_FORMATTER = DateTimeFormatter.ofPattern("dd-MMM-yyyy HH:mm", Locale.ENGLISH);

    // SQL Queries (loaded from external .sql files with lowercase first word + CamelCase filenames)
    private static final String SQL_CREATE_VEHICLE = QueryLoader.getQuery("vehicle/insertVehicle.sql");
    private static final String SQL_READ_VEHICLE_BY_ID = QueryLoader.getQuery("vehicle/selectVehicleById.sql");
    private static final String SQL_READ_ALL_VEHICLES = QueryLoader.getQuery("vehicle/selectVehiclesAll.sql");
    private static final String SQL_COUNT_VEHICLES = QueryLoader.getQuery("vehicle/selectCountVehicles.sql");
    private static final String SQL_EXISTS_VEHICLE_BY_ID = QueryLoader.getQuery("vehicle/selectExistsVehicleById.sql");
    private static final String SQL_UPDATE_VEHICLE = QueryLoader.getQuery("vehicle/updateVehicle.sql");
    private static final String SQL_SOFT_DELETE_VEHICLE = QueryLoader.getQuery("vehicle/deleteVehicleSoft.sql");
    private static final String SQL_FIND_BY_VEHICLE_NUMBER = QueryLoader.getQuery("vehicle/selectVehicleByVehicleNumber.sql");
    private static final String SQL_FIND_ACTIVE_VEHICLE = QueryLoader.getQuery("vehicle/selectActiveVehicle.sql");
    private static final String SQL_FIND_BY_MAKE = QueryLoader.getQuery("vehicle/selectVehiclesByMake.sql");
    private static final String SQL_FIND_BY_MODEL = QueryLoader.getQuery("vehicle/selectVehiclesByModel.sql");
    private static final String SQL_FIND_BY_YEAR = QueryLoader.getQuery("vehicle/selectVehiclesByYear.sql");

    /**
     * Maps a {@link ResultSet} row to a {@link Vehicle} object.
     * This private helper method centralizes the logic for creating Vehicle objects from database results.
     * Ensures mapping aligns with schema's nullable and NOT NULL constraints.
     *
     * @param rs The {@link ResultSet} positioned at the current row.
     * @return A {@link Vehicle} object populated with data from the ResultSet.
     * @throws SQLException If a column is not found or other database access errors occur.
     */
    private Vehicle mapResultSetToVehicle(ResultSet rs) throws SQLException {
        Integer vehicleID = rs.getInt("VehicleID"); // NOT NULL in schema, but SQLite's INTEGER PRIMARY KEY is nullable on read
        String vehicleNumber = rs.getString("VehicleNumber"); // NOT NULL
        String make = rs.getString("Make"); // Nullable
        String model = rs.getString("Model"); // Nullable
        Integer year = rs.getObject("Year", Integer.class); // Nullable, use getObject
        Integer capacity = rs.getInt("Capacity"); // NOT NULL, use getInt

        // Handle LeaseStartDate (TEXT in DB, LocalDate in Java, NOT NULL)
        LocalDate leaseStartDate = LocalDate.parse(rs.getString("LeaseStartDate"), CUSTOM_DATE_FORMATTER);

        // Handle LeaseEndDate (TEXT in DB, LocalDate in Java, Nullable)
        LocalDate leaseEndDate = null;
        String leaseEndDateStr = rs.getString("LeaseEndDate");
        if (leaseEndDateStr != null && !leaseEndDateStr.isEmpty()) {
            leaseEndDate = LocalDate.parse(leaseEndDateStr, CUSTOM_DATE_FORMATTER);
        }

        // --- CORRECTED: Use BigDecimal for discount ---
        BigDecimal discount = rs.getObject("Discount", BigDecimal.class); // Nullable (has default 0), use getObject

        boolean isActive = rs.getInt("IsActive") == 1; // NOT NULL

        // Handle DeletedAt (TEXT in DB, LocalDateTime in Java, Nullable)
        LocalDateTime deletedAt = null;
        String deletedAtStr = rs.getString("DeletedAt");
        if (deletedAtStr != null && !deletedAtStr.isEmpty()) {
            deletedAt = LocalDateTime.parse(deletedAtStr, CUSTOM_DATETIME_FORMATTER);
        }

        String notes = rs.getString("Notes"); // Nullable

        return new Vehicle(
                vehicleID, vehicleNumber, make, model, year, capacity,
                leaseStartDate, leaseEndDate, discount, isActive, deletedAt, notes
        );
    }

    // --- CreateDataAccess Implementation ---

    /**
     * <p>
     * Inserts a new vehicle record into the SQLite database.
     * The database's AUTOINCREMENT feature assigns a unique `VehicleID`.
     * </p>
     * <p>
     * The `VehicleNumber`, `Capacity`, `LeaseStartDate`, `IsActive` must be provided and are NOT NULL.
     * The service layer is responsible for business rules like "only one active vehicle".
     * </p>
     *
     * @param vehicle The {@link Vehicle} object to be created. Its `VehicleID` will be ignored if present.
     * @return The created {@link Vehicle} object with its database-assigned ID.
     * @throws DatabaseAccessException if a database access error occurs during creation,
     * e.g., if `VehicleNumber` already exists (SQL UNIQUE constraint violation).
     * @throws NullPointerException    if the provided vehicle object or its required `NOT NULL` fields are {@code null}.
     */
    @Override
    public Vehicle createRecord(Vehicle vehicle) throws DatabaseAccessException {
        Objects.requireNonNull(vehicle, "Vehicle cannot be null for createRecord.");
        Objects.requireNonNull(vehicle.getVehicleNumber(), "Vehicle number cannot be null for createRecord.");
        Objects.requireNonNull(vehicle.getCapacity(), "Vehicle capacity cannot be null for createRecord (NOT NULL constraint).");
        Objects.requireNonNull(vehicle.getLeaseStartDate(), "Vehicle lease start date cannot be null for createRecord (NOT NULL constraint).");
        // IsActive is primitive boolean, so it's never null.

        String vehicleNumber = vehicle.getVehicleNumber().trim();
        if (vehicleNumber.isEmpty()) {
            throw new DatabaseAccessException("Vehicle number cannot be empty for createRecord.");
        }

        try (Connection connection = DatabaseManager.getConnection();
             // RETURN_GENERATED_KEYS is crucial for getting the auto-incremented ID
             PreparedStatement pstmt = connection.prepareStatement(SQL_CREATE_VEHICLE, Statement.RETURN_GENERATED_KEYS)) {

            int paramIndex = 1;
            pstmt.setString(paramIndex++, vehicleNumber);
            pstmt.setString(paramIndex++, vehicle.getMake()); // Nullable
            pstmt.setString(paramIndex++, vehicle.getModel()); // Nullable
            pstmt.setObject(paramIndex++, vehicle.getYear(), java.sql.Types.INTEGER); // Nullable
            pstmt.setInt(paramIndex++, vehicle.getCapacity()); // NOT NULL
            pstmt.setString(paramIndex++, vehicle.getLeaseStartDate().format(CUSTOM_DATE_FORMATTER)); // NOT NULL
            pstmt.setString(paramIndex++, vehicle.getLeaseEndDate() != null ? vehicle.getLeaseEndDate().format(CUSTOM_DATE_FORMATTER) : null); // Nullable
            // --- CORRECTED: Use setBigDecimal for discount ---
            pstmt.setBigDecimal(paramIndex++, vehicle.getDiscount()); // Nullable (NUMERIC in schema)
            pstmt.setInt(paramIndex++, vehicle.isActive() ? 1 : 0); // NOT NULL
            pstmt.setString(paramIndex++, vehicle.getDeletedAt() != null ? vehicle.getDeletedAt().format(CUSTOM_DATETIME_FORMATTER) : null); // Nullable
            pstmt.setString(paramIndex++, vehicle.getNotes()); // Nullable

            int affectedRows = pstmt.executeUpdate();
            if (affectedRows == 0) {
                logger.error("Creating vehicle failed, no rows affected for vehicle number: {}", vehicle.getVehicleNumber());
                throw new DatabaseAccessException("Creating vehicle failed, no rows affected.");
            }

            try (ResultSet generatedKeys = pstmt.getGeneratedKeys()) {
                if (generatedKeys.next()) {
                    int id = generatedKeys.getInt(1); // Get the auto-generated ID
                    logger.info("Vehicle created with ID: {}", id);
                    // Return a new Vehicle object with the assigned ID from the database
                    return new Vehicle(
                            id,
                            vehicle.getVehicleNumber(),
                            vehicle.getMake(),
                            vehicle.getModel(),
                            vehicle.getYear(),
                            vehicle.getCapacity(),
                            vehicle.getLeaseStartDate(),
                            vehicle.getLeaseEndDate(),
                            vehicle.getDiscount(),
                            vehicle.isActive(),
                            vehicle.getDeletedAt(),
                            vehicle.getNotes()
                    );
                } else {
                    logger.error("Creating vehicle failed, no ID obtained for vehicle number: {}", vehicle.getVehicleNumber());
                    throw new DatabaseAccessException("Creating vehicle failed, no ID obtained.");
                }
            }

        } catch (SQLException e) {
            String errorMsg = "Error creating vehicle '" + vehicle.getVehicleNumber() + "': " + e.getMessage();
            logger.error(errorMsg, e);
            // Check for specific SQL error codes for unique constraint violation (SQLite: 19)
            if (e.getErrorCode() == 19) { // SQLite constraint violation error code
                throw new DatabaseAccessException("Vehicle with number '" + vehicle.getVehicleNumber() + "' already exists.", e);
            }
            throw new DatabaseAccessException(errorMsg, e);
        }
    }

    // --- ReadDataAccess Implementation ---

    @Override
    public Optional<Vehicle> readRecord(Integer id) throws DatabaseAccessException {
        Objects.requireNonNull(id, "Vehicle ID cannot be null for readRecord.");

        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_READ_VEHICLE_BY_ID)) {

            pstmt.setInt(1, id);
            try (ResultSet rs = pstmt.executeQuery()) {
                if (rs.next()) {
                    return Optional.of(mapResultSetToVehicle(rs));
                }
            }
            return Optional.empty(); // Not found
        } catch (SQLException e) {
            String errorMsg = "Error reading vehicle with ID " + id + ": " + e.getMessage();
            logger.error(errorMsg, e);
            throw new DatabaseAccessException(errorMsg, e);
        }
    }

    @Override
    public List<Vehicle> readRecordAll() throws DatabaseAccessException {
        List<Vehicle> vehicles = new ArrayList<>();
        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_READ_ALL_VEHICLES);
             ResultSet rs = pstmt.executeQuery()) {

            while (rs.next()) {
                vehicles.add(mapResultSetToVehicle(rs));
            }
            return vehicles;
        } catch (SQLException e) {
            String errorMsg = "Error reading all vehicles: " + e.getMessage();
            logger.error(errorMsg, e);
            throw new DatabaseAccessException(errorMsg, e);
        }
    }

    @Override
    public long countRecord() throws DatabaseAccessException {
        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_COUNT_VEHICLES);
             ResultSet rs = pstmt.executeQuery()) {

            if (rs.next()) {
                return rs.getLong(1); // Get the count
            }
            return 0;
        } catch (SQLException e) {
            String errorMsg = "Error counting vehicles: " + e.getMessage();
            logger.error(errorMsg, e);
            throw new DatabaseAccessException(errorMsg, e);
        }
    }

    @Override
    public boolean existsById(Integer id) throws DatabaseAccessException {
        Objects.requireNonNull(id, "Vehicle ID cannot be null for existsById.");

        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_EXISTS_VEHICLE_BY_ID)) {

            pstmt.setInt(1, id);
            try (ResultSet rs = pstmt.executeQuery()) {
                return rs.next(); // If there's a row, it exists
            }
        } catch (SQLException e) {
            String errorMsg = "Error checking existence for vehicle with ID " + id + ": " + e.getMessage();
            logger.error(errorMsg, e);
            throw new DatabaseAccessException(errorMsg, e);
        }
    }

    // --- UpdateDataAccess Implementation ---

    @Override
    public void updateRecord(Vehicle vehicle) throws DatabaseAccessException {
        Objects.requireNonNull(vehicle, "Vehicle cannot be null for updateRecord.");
        Objects.requireNonNull(vehicle.getVehicleID(), "Vehicle ID cannot be null for updateRecord.");
        Objects.requireNonNull(vehicle.getVehicleNumber(), "Vehicle number cannot be null for updateRecord.");
        Objects.requireNonNull(vehicle.getCapacity(), "Vehicle capacity cannot be null for updateRecord (NOT NULL constraint).");
        Objects.requireNonNull(vehicle.getLeaseStartDate(), "Vehicle lease start date cannot be null for updateRecord (NOT NULL constraint).");

        String vehicleNumber = vehicle.getVehicleNumber().trim();
        if (vehicleNumber.isEmpty()) {
            throw new DatabaseAccessException("Vehicle number cannot be empty for updateRecord.");
        }

        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_UPDATE_VEHICLE)) {

            int paramIndex = 1;
            pstmt.setString(paramIndex++, vehicleNumber);
            pstmt.setString(paramIndex++, vehicle.getMake()); // Nullable
            pstmt.setString(paramIndex++, vehicle.getModel()); // Nullable
            pstmt.setObject(paramIndex++, vehicle.getYear(), java.sql.Types.INTEGER); // Nullable
            pstmt.setInt(paramIndex++, vehicle.getCapacity()); // NOT NULL
            pstmt.setString(paramIndex++, vehicle.getLeaseStartDate().format(CUSTOM_DATE_FORMATTER)); // NOT NULL
            pstmt.setString(paramIndex++, vehicle.getLeaseEndDate() != null ? vehicle.getLeaseEndDate().format(CUSTOM_DATE_FORMATTER) : null); // Nullable
            // --- CORRECTED: Use setBigDecimal for discount ---
            pstmt.setBigDecimal(paramIndex++, vehicle.getDiscount()); // Nullable (NUMERIC in schema)
            pstmt.setInt(paramIndex++, vehicle.isActive() ? 1 : 0); // NOT NULL
            pstmt.setString(paramIndex++, vehicle.getDeletedAt() != null ? vehicle.getDeletedAt().format(CUSTOM_DATETIME_FORMATTER) : null); // Nullable
            pstmt.setString(paramIndex++, vehicle.getNotes()); // Nullable
            pstmt.setInt(paramIndex++, vehicle.getVehicleID()); // WHERE clause parameter

            int affectedRows = pstmt.executeUpdate();
            if (affectedRows == 0) {
                logger.warn("Update failed: Vehicle with ID {} not found or no changes made.", vehicle.getVehicleID());
                throw new DatabaseAccessException("Vehicle with ID " + vehicle.getVehicleID() + " not found for update.");
            } else {
                logger.info("Vehicle with ID {} updated successfully.", vehicle.getVehicleID());
            }
        } catch (SQLException e) {
            String errorMsg = "Error updating vehicle with ID " + vehicle.getVehicleID() + ": " + e.getMessage();
            logger.error(errorMsg, e);
            if (e.getErrorCode() == 19) { // SQLite constraint violation error code
                throw new DatabaseAccessException("Update failed: Vehicle with number '" + vehicle.getVehicleNumber() + "' already exists for another vehicle.", e);
            }
            throw new DatabaseAccessException(errorMsg, e);
        }
    }

    // --- GenericDataAccess Implementation (Soft Delete) ---

    @Override
    public void deleteRecord(Integer id) throws DatabaseAccessException {
        Objects.requireNonNull(id, "Vehicle ID cannot be null for deleteRecord.");

        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_SOFT_DELETE_VEHICLE)) {

            pstmt.setInt(1, 0); // IsActive = 0 (false)
            pstmt.setString(2, LocalDateTime.now().format(CUSTOM_DATETIME_FORMATTER)); // DeletedAt = current timestamp
            pstmt.setInt(3, id); // WHERE VehicleID = id

            int affectedRows = pstmt.executeUpdate();
            if (affectedRows == 0) {
                logger.warn("Soft-delete failed: Vehicle with ID {} not found.", id);
                throw new DatabaseAccessException("Vehicle with ID " + id + " not found for soft-deletion.");
            } else {
                logger.info("Vehicle with ID {} soft-deleted successfully.", id);
            }
        } catch (SQLException e) {
            String errorMsg = "Error soft-deleting vehicle with ID " + id + ": " + e.getMessage();
            logger.error(errorMsg, e);
            throw new DatabaseAccessException(errorMsg, e);
        }
    }

    // --- VehicleDataAccess Specific Implementations ---

    @Override
    public Optional<Vehicle> findByVehicleNumber(String vehicleNumber) throws DatabaseAccessException {
        Objects.requireNonNull(vehicleNumber, "Vehicle number cannot be null for findByVehicleNumber.");
        String trimmedVehicleNumber = vehicleNumber.trim();
        if (trimmedVehicleNumber.isEmpty()) {
            throw new DatabaseAccessException("Vehicle number cannot be empty for findByVehicleNumber.");
        }

        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_FIND_BY_VEHICLE_NUMBER)) {

            pstmt.setString(1, trimmedVehicleNumber);
            try (ResultSet rs = pstmt.executeQuery()) {
                if (rs.next()) {
                    return Optional.of(mapResultSetToVehicle(rs));
                }
            }
            return Optional.empty();
        } catch (SQLException e) {
            String errorMsg = "Error finding vehicle by number '" + trimmedVehicleNumber + "': " + e.getMessage();
            logger.error(errorMsg, e);
            throw new DatabaseAccessException(errorMsg, e);
        }
    }

    @Override
    public Optional<Vehicle> findActiveVehicle() throws DatabaseAccessException {
        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_FIND_ACTIVE_VEHICLE);
             ResultSet rs = pstmt.executeQuery()) {

            // As per business rule, there should be at most one.
            if (rs.next()) {
                Vehicle activeVehicle = mapResultSetToVehicle(rs);
                if (rs.next()) { // Check if there's a second active vehicle (data integrity issue)
                    String warningMsg = "WARNING: Multiple active vehicles found, violating business rule! " +
                            "IDs: " + activeVehicle.getVehicleID() + ", " + rs.getInt("VehicleID") + " and possibly more.";
                    logger.warn(warningMsg);
                    // For now, return the first one found, but this indicates a problem to be addressed at service layer.
                }
                return Optional.of(activeVehicle);
            }
            return Optional.empty();
        } catch (SQLException e) {
            String errorMsg = "Error finding active vehicle: " + e.getMessage();
            logger.error(errorMsg, e);
            throw new DatabaseAccessException(errorMsg, e);
        }
    }

