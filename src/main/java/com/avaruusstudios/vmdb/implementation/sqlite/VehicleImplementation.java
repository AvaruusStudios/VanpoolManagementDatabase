    /**
     * <p>
     * Inserts a new {@link Vehicle} record into the SQLite database.
     * Upon successful insertion, the database-generated `VehicleID` is
     * injected back into the provided {@link Vehicle} object via its
     * package-private `_setVehicleID` method.
     * </p>
     * <p>
     * This method validates essential {@code Vehicle} properties before execution
     * and handles potential SQL exceptions, rethrowing them as {@link DatabaseAccessException}.
     * It also specifically catches unique constraint violations for `VehicleNumber`.
     * </p>
     *
     * @param vehicle The {@link Vehicle} object containing the data to be inserted.
     * Its `VehicleID` should typically be `null` or ignored as it's
     * auto-generated by the database.
     * @return The same {@link Vehicle} object, updated with its new database-assigned `VehicleID`.
     * @throws DatabaseAccessException if a database access error occurs (e.g., connection issues,
     * SQL syntax errors, or a `VehicleNumber` unique constraint violation).
     * @throws NullPointerException    if the provided {@code vehicle} object itself, or any of its
     * mandatory (NOT NULL) fields (`VehicleNumber`, `Capacity`, `LeaseStartDate`), is {@code null}.
     * @throws IllegalArgumentException if `VehicleNumber` is an empty string after trimming.
     */
    @Override
    public Vehicle createRecord(Vehicle vehicle) throws DatabaseAccessException {
        // Pre-conditions: Validate input object and its essential properties.
        Objects.requireNonNull(vehicle, "Vehicle cannot be null for createRecord.");
        Objects.requireNonNull(vehicle.getVehicleNumber(), "Vehicle number cannot be null for createRecord.");
        Objects.requireNonNull(vehicle.getCapacity(), "Vehicle capacity cannot be null for createRecord (NOT NULL constraint).");
        Objects.requireNonNull(vehicle.getLeaseStartDate(), "Vehicle lease start date cannot be null for createRecord (NOT NULL constraint).");
        // vehicle.isActive() is a primitive boolean, so it cannot be null.

        String vehicleNumber = vehicle.getVehicleNumber().trim();
        if (vehicleNumber.isEmpty()) {
            throw new IllegalArgumentException("Vehicle number cannot be empty for createRecord.");
        }

        try (Connection connection = DatabaseManager.getConnection();
             // Prepare the statement to return auto-generated keys (the VehicleID)
             PreparedStatement pstmt = connection.prepareStatement(SQL_CREATE_VEHICLE, Statement.RETURN_GENERATED_KEYS)) {

            int paramIndex = 1;
            // Set parameters for the PreparedStatement, handling nullable fields appropriately.
            pstmt.setString(paramIndex++, vehicleNumber);
            pstmt.setString(paramIndex++, vehicle.getMake()); // Nullable
            pstmt.setString(paramIndex++, vehicle.getModel()); // Nullable
            // Use setInt for non-null year, setNull for null Integer year with Types.INTEGER.
            if (vehicle.getYear() != null) {
                pstmt.setInt(paramIndex++, vehicle.getYear());
            } else {
                pstmt.setNull(paramIndex++, Types.INTEGER);
            }
            pstmt.setInt(paramIndex++, vehicle.getCapacity()); // NOT NULL
            pstmt.setString(paramIndex++, vehicle.getLeaseStartDate().format(CUSTOM_DATE_FORMATTER)); // NOT NULL
            pstmt.setString(paramIndex++, vehicle.getLeaseEndDate() != null ? vehicle.getLeaseEndDate().format(CUSTOM_DATE_FORMATTER) : null); // Nullable
            // Use setBigDecimal for BigDecimal, setNull with Types.NUMERIC for nulls.
            if (vehicle.getDiscount() != null) {
                pstmt.setBigDecimal(paramIndex++, vehicle.getDiscount());
            } else {
                pstmt.setNull(paramIndex++, Types.NUMERIC);
            }
            pstmt.setInt(paramIndex++, vehicle.isActive() ? 1 : 0); // NOT NULL (boolean to int)
            pstmt.setString(paramIndex++, vehicle.getDeletedAt() != null ? vehicle.getDeletedAt().format(CUSTOM_DATETIME_FORMATTER) : null); // Nullable
            pstmt.setString(paramIndex++, vehicle.getNotes()); // Nullable

            int affectedRows = pstmt.executeUpdate(); // Execute the insert operation
            if (affectedRows == 0) {
                logger.error("Creating vehicle failed, no rows affected for vehicle number: {}.", vehicle.getVehicleNumber());
                throw new DatabaseAccessException("Creating vehicle failed, no rows affected.");
            }

            // Retrieve the auto-generated VehicleID
            try (ResultSet generatedKeys = pstmt.getGeneratedKeys()) {
                if (generatedKeys.next()) {
                    int id = generatedKeys.getInt(1); // Get the first (and only) generated key
                    logger.info("Vehicle created successfully with ID: {}.", id);
                    // Update the *original* vehicle object with the database-assigned ID.
                    vehicle._setVehicleID(id);
                    return vehicle; // Return the updated object
                } else {
                    logger.error("Creating vehicle failed, no ID obtained for vehicle number: {}.", vehicle.getVehicleNumber());
                    throw new DatabaseAccessException("Creating vehicle failed, no ID obtained.");
                }
            }

        } catch (SQLException e) {
            String errorMsg = "Error creating vehicle '" + vehicle.getVehicleNumber() + "': " + e.getMessage();
            logger.error(errorMsg, e);
            // Check for specific SQL error code for unique constraint violation (SQLite error code 19)
            if (e.getErrorCode() == 19) {
                throw new DatabaseAccessException("Vehicle with number '" + vehicle.getVehicleNumber() + "' already exists. Vehicle numbers must be unique.", e);
            }
            throw new DatabaseAccessException(errorMsg, e);
        }
    }

