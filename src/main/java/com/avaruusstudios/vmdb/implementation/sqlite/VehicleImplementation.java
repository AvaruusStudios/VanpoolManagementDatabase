    /**
     * <p>
     * Maps a row from a {@link ResultSet} to a {@link Vehicle} object.
     * This private helper method centralizes the logic for creating {@code Vehicle} objects
     * from database results, ensuring consistency in data retrieval.
     * </p>
     * <p>
     * It handles different data types, including nullable numeric ({@link Integer}, {@link BigDecimal}),
     * date ({@link LocalDate}), and datetime ({@link LocalDateTime}) fields,
     * converting them from their SQLite `TEXT`/`INTEGER`/`NUMERIC` representations to appropriate Java types.
     * </p>
     *
     * @param rs The {@link ResultSet} positioned at the current row containing vehicle data.
     * @return A {@link Vehicle} object populated with data from the {@code ResultSet}.
     * @throws SQLException If a column is not found in the {@code ResultSet}, a data type
     * conversion error occurs, or any other database access error occurs.
     */
    private Vehicle mapResultSetToVehicle(ResultSet rs) throws SQLException {
        // Create a new Vehicle object using its default constructor.
        Vehicle vehicle = new Vehicle();

        // Retrieve and set the VehicleID. SQLite returns 0 for NULL INT columns if using getInt directly,
        // so check for positive value. The _setVehicleID method enforces immutability and validation.
        Integer vehicleID = rs.getInt("VehicleID");
        if (vehicleID > 0) { // Valid IDs are positive
            vehicle._setVehicleID(vehicleID);
        }

        // Set other properties by retrieving values from the ResultSet and using the Vehicle's public setters.
        vehicle.setVehicleNumber(rs.getString("VehicleNumber"));
        vehicle.setMake(rs.getString("Make"));
        vehicle.setModel(rs.getString("Model"));

        // For nullable Integer 'Year', use getObject with Integer.class to correctly handle nulls from DB.
        vehicle.setYear(rs.getObject("Year", Integer.class));

        vehicle.setCapacity(rs.getInt("Capacity")); // NOT NULL, int automatically handles non-null

        // Handle LeaseStartDate (TEXT in DB -> LocalDate in Java, NOT NULL).
        vehicle.setLeaseStartDate(LocalDate.parse(rs.getString("LeaseStartDate"), CUSTOM_DATE_FORMATTER));

        // Handle LeaseEndDate (TEXT in DB -> LocalDate in Java, Nullable).
        String leaseEndDateStr = rs.getString("LeaseEndDate");
        vehicle.setLeaseEndDate(leaseEndDateStr != null && !leaseEndDateStr.isEmpty() ?
                LocalDate.parse(leaseEndDateStr, CUSTOM_DATE_FORMATTER) : null);

        // Handle Discount (NUMERIC/REAL in DB -> BigDecimal in Java, Nullable).
        // Use getObject with BigDecimal.class for robust null handling of numeric types.
        vehicle.setDiscount(rs.getObject("Discount", BigDecimal.class));

        // Handle IsActive (INTEGER in DB -> boolean in Java, NOT NULL). SQLite stores booleans as 0 or 1.
        vehicle.setIsActive(rs.getInt("IsActive") == 1);

        // Handle DeletedAt (TEXT in DB -> LocalDateTime in Java, Nullable).
        String deletedAtStr = rs.getString("DeletedAt");
        vehicle.setDeletedAt(deletedAtStr != null && !deletedAtStr.isEmpty() ?
                LocalDateTime.parse(deletedAtStr, CUSTOM_DATETIME_FORMATTER) : null);

        vehicle.setNotes(rs.getString("Notes")); // Nullable, getString returns null for DB NULL

        return vehicle;
    }

