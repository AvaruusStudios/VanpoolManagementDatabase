    /**
     * <p>
     * Soft-deletes a {@link Vehicle} record from the database by setting its `IsActive` flag
     * to `0` (false) and updating the `DeletedAt` timestamp to the current date and time.
     * This method does not physically remove the record, preserving historical data.
     * </p>
     *
     * @param id The unique integer ID of the vehicle to soft-delete. Must not be {@code null} and must be positive.
     * @throws DatabaseAccessException  if a database access error occurs during deletion.
     * @throws NullPointerException     if the provided {@code id} is {@code null}.
     * @throws IllegalArgumentException if the provided {@code id} is non-positive.
     */
    @Override
    public void deleteRecord(Integer id) throws DatabaseAccessException {
        Objects.requireNonNull(id, "Vehicle ID cannot be null for deleteRecord.");
        if (id <= 0) {
            throw new IllegalArgumentException("Vehicle ID must be positive for deleteRecord.");
        }

        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_SOFT_DELETE_VEHICLE)) {

            pstmt.setInt(1, 0); // Set IsActive to false (0)
            pstmt.setString(2, LocalDateTime.now().format(CUSTOM_DATETIME_FORMATTER)); // Set DeletedAt to current timestamp
            pstmt.setInt(3, id); // WHERE clause parameter (ID of the vehicle to soft-delete)

            int affectedRows = pstmt.executeUpdate(); // Execute the update operation
            if (affectedRows == 0) {
                logger.warn("Soft-delete failed: Vehicle with ID {} not found.", id);
                throw new DatabaseAccessException("Vehicle with ID " + id + " not found for soft-deletion.");
            } else {
                logger.info("Vehicle with ID {} soft-deleted successfully.", id);
            }
        } catch (SQLException e) {
            String errorMsg = "Error soft-deleting vehicle with ID " + id + ": " + e.getMessage();
            logger.error(errorMsg, e);
            throw new DatabaseAccessException(errorMsg, e);
        }
    }

