    /**
     * <p>
     * Retrieves a single {@link Vehicle} record from the database by its unique identifier.
     * </p>
     *
     * @param id The unique integer ID of the vehicle to retrieve. Must not be {@code null} and must be positive.
     * @return An {@link Optional} containing the {@link Vehicle} object if found,
     * or an empty {@link Optional} if no vehicle with the given ID exists.
     * @throws DatabaseAccessException  if a database access error occurs during retrieval.
     * @throws NullPointerException     if the provided {@code id} is {@code null}.
     * @throws IllegalArgumentException if the provided {@code id} is non-positive.
     */
    @Override
    public Optional<Vehicle> readRecord(Integer id) throws DatabaseAccessException {
        Objects.requireNonNull(id, "Vehicle ID cannot be null for readRecord.");
        if (id <= 0) {
            throw new IllegalArgumentException("Vehicle ID must be positive for readRecord.");
        }

        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_READ_VEHICLE_BY_ID)) {

            pstmt.setInt(1, id); // Set the ID parameter
            try (ResultSet rs = pstmt.executeQuery()) {
                if (rs.next()) {
                    // If a record is found, map it to a Vehicle object.
                    return Optional.of(mapResultSetToVehicle(rs));
                }
            }
            return Optional.empty(); // No record found with the given ID
        } catch (SQLException e) {
            String errorMsg = "Error reading vehicle with ID " + id + ": " + e.getMessage();
            logger.error(errorMsg, e);
            throw new DatabaseAccessException(errorMsg, e);
        }
    }

    /**
     * <p>
     * Retrieves all {@link Vehicle} records currently stored in the database.
     * </p>
     *
     * @return A {@link List} of {@link Vehicle} objects. The list will be empty if no vehicles are found.
     * @throws DatabaseAccessException if a database access error occurs during retrieval.
     */
    @Override
    public List<Vehicle> readRecordAll() throws DatabaseAccessException {
        List<Vehicle> vehicles = new ArrayList<>();
        try (Connection connection = DatabaseManager.getConnection();
             PreparedStatement pstmt = connection.prepareStatement(SQL_READ_ALL_VEHICLES);
             ResultSet rs = pstmt.executeQuery()) { // Execute query directly since no parameters

            while (rs.next()) {
                // Iterate through the ResultSet and map each row to a Vehicle object.
                vehicles.add(mapResultSetToVehicle(rs));
            }
            return vehicles;
        } catch (SQLException e) {
            String errorMsg = "Error reading all vehicles: " + e.getMessage();
            logger.error(errorMsg, e);
            throw new DatabaseAccessException(errorMsg, e);
        }
    }

